/**
 * Verilen oda alan tipi metnine (ve varsa kurum turune) gore en uygun
 * checklist kaynagini bulur -- Desktop'un kaynak_onerileri() (FK tabanli
 * kademeli oneri) ile AYNI amaca hizmet eder ama PWA'nin daha basit
 * veri modeline (serbest metin alanTipi, FK yok) uygun basit anahtar-
 * kelime eslesmesi kullanir. Eslesme yoksa null doner -- chip satiri
 * HIC gosterilmez (zorunlu degil, pasif hatirlatma ilkesi).
 */
function checklistKaynagiBul(alanTipi, kurumTuru) {
  const metin = String(alanTipi || '').toLocaleLowerCase('tr-TR');
  for (const [kod, kaynak] of Object.entries(CHECKLIST_KUTUPHANESI)) {
    if (kaynak.anahtarKelimeler.some((k) => metin.includes(k))) return kod;
  }
  if (kurumTuru === 'santiye') return 'csgb_kucuk_insaatlar';
  if (kurumTuru === 'hastane') return 'csgb_eczaneler';
  return null;
}

if (typeof window !== 'undefined') {
  window.CHECKLIST_KUTUPHANESI = CHECKLIST_KUTUPHANESI;
  window.checklistKaynagiBul = checklistKaynagiBul;
}
